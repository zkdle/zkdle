// Emit the verifying key as Rust constants for groth16-solana.
const vk = require('../zk/vk.json');
const { be32 } = require('../zk/lib');
const g1 = (p) => Buffer.concat([be32(p[0]), be32(p[1])]);
const g2 = (p) => Buffer.concat([be32(p[0][1]), be32(p[0][0]), be32(p[1][1]), be32(p[1][0])]);
const arr = (b) => '[' + [...b].join(', ') + ']';
let out = '// generated by scripts/vk2rs.js — do not edit\nuse groth16_solana::groth16::Groth16Verifyingkey;\n\n';
out += `pub const IC: [[u8; 64]; ${vk.IC.length}] = [\n${vk.IC.map((p) => '    ' + arr(g1(p))).join(',\n')}\n];\n\n`;
out += `pub const VK: Groth16Verifyingkey = Groth16Verifyingkey {\n    nr_pubinputs: ${vk.nPublic},\n    vk_alpha_g1: ${arr(g1(vk.vk_alpha_1))},\n    vk_beta_g2: ${arr(g2(vk.vk_beta_2))},\n    vk_gamme_g2: ${arr(g2(vk.vk_gamma_2))},\n    vk_delta_g2: ${arr(g2(vk.vk_delta_2))},\n    vk_ic: &IC,\n};\n`;
require('fs').writeFileSync(require('path').join(__dirname, '../program/src/vk.rs'), out);
